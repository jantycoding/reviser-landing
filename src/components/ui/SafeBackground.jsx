import { Component } from 'react';

/**
 * Предохранитель для декоративных WebGL-фонов.
 *
 * Зачем. Фон первого экрана (Prism, до него Aurora и FloatingLines) создаёт
 * WebGL-контекст в момент монтирования. Если контекст не выдаётся — старый
 * Android, отключённое аппаратное ускорение, режим экономии батареи, лимит
 * одновременных контекстов в браузере — конструктор бросает исключение. Без
 * границы ошибок React снимает всё дерево целиком, и человек видит не «фон
 * не загрузился», а белый экран вместо сайта.
 *
 * Цена ошибки здесь несимметрична: фон — украшение, страница — источник
 * денег. Поэтому любой сбой внутри проглатывается, и на месте фона остаётся
 * пустота, поверх которой и так лежит градиент в цвет фона страницы.
 * Пользователь разницы не заметит.
 *
 * Границы ошибок в React обязаны быть классовыми — хуками это не пишется.
 */
export default class SafeBackground extends Component {
  constructor(props) {
    super(props);
    this.state = { failed: false };
  }

  static getDerivedStateFromError() {
    return { failed: true };
  }

  componentDidCatch(error) {
    // Не молча: в консоли причина остаётся, чтобы её можно было найти.
    if (typeof console !== 'undefined') {
      console.warn('[Reviser] фон первого экрана не запустился, страница работает дальше:', error);
    }
  }

  render() {
    if (this.state.failed) return null;
    return this.props.children;
  }
}
