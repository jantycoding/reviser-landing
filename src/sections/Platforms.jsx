import { useEffect, useRef } from 'react';
import Marquee from '../components/ui/Marquee';
import PlatformIcon from '../components/ui/PlatformIcon';
import Reveal from '../components/ui/Reveal';
import { platforms } from '../content/site';

/**
 * Лента платформ, к которым подключаются агенты.
 *
 * ⚠️ Здесь намеренно НЕ логотипы клиентов. Ставить чужие бренды в роли своих
 * клиентов нельзя: это нарушение рекламной политики Meta (а трафик идёт
 * оттуда), претензии по товарным знакам и мгновенная потеря доверия рынка,
 * где предприниматели общаются между собой. Лента платформ даёт тот же
 * визуальный эффект «эти ребята в теме» и при этом правдива.
 *
 * ПЕРЕОФОРМЛЕНИЕ 26.08.2026 (запрос владельца)
 * ────────────────────────────────────────────
 * 1. Точки → значки. Мятая точка перед каждым названием была одинаковой у
 *    всех пятнадцати строк и не несла ни грамма информации: она сообщала
 *    «пункт списка» там, где пункт списка и так очевиден. Значок сообщает
 *    ТИП связи — канал, CRM, платежи, карты, — и человек считывает охват
 *    ленты, не читая подписи.
 * 2. Секция больше не во всю ширину экрана. Было edge-to-edge, стало —
 *    контейнер с полями: лента шире колонки текста (максимум 84rem против
 *    72rem у заголовка), но до края монитора не достаёт. На широком экране
 *    полоса от рамки до рамки читается как чужой блок, вклеенный в страницу.
 * 3. Рамка секции заменена на пунктир сверху — тот же разделитель, что у
 *    остальных секций (см. components/ui/Section.jsx). Сплошная линия здесь
 *    была единственной на всей странице.
 */
function Item({ label, icon }) {
  /**
   * Рамка и заливка сняты 26.08.2026 (запрос владельца: «без контейнера,
   * просто значок и подпись снизу»). Это не только вкус: пятнадцать
   * одинаковых серых плашек в бегущей строке создавали второй слой рамок
   * поверх и без того обведённых секций страницы, и глаз читал ряд как
   * «карточки», хотя это просто перечисление. Без плашек ряд стал
   * перечислением, каким и является.
   *
   * Значок вырос с 18 до 32 пикселей и переехал НАД подписью. В строке
   * значок 18px рядом с текстом 16px был мельче буквы и не читался —
   * ровно то, на что владелец и указал. Сверху, по центру, вдвое крупнее
   * текста — он становится тем, что видно первым, а подпись объясняет.
   *
   * Горизонтальные поля px-7 заменяют исчезнувшие рамки: без них подписи
   * соседних платформ («Google Sheets» и «Meta Ads») слипались в одну
   * строку, потому что разделять их стало нечем.
   *
   * Ширина — по содержимому, с нижним пределом 7.5rem, а НЕ фиксированная.
   * Фиксированные 8.5rem держали короткие подписи ровно, но «WhatsApp
   * Business» в них не влезал: nowrap выносил текст за границы блока, и он
   * налезал на соседа. Ровность сетки здесь не нужна — элементы всё равно
   * едут мимо глаза, а вот наползающие подписи видны сразу.
   */
  return (
    <span className="flex min-w-[7.5rem] flex-col items-center gap-3 px-7 text-center">
      <PlatformIcon name={icon} className="h-10 w-10 shrink-0 text-fog" />
      <span className="text-fine whitespace-nowrap text-fog">{label}</span>
    </span>
  );
}

export default function Platforms() {
  const sectionRef = useRef(null);

  /**
   * Лента крутится только пока секция в кадре.
   * Страница высотой ~12 000px, а анимация бесконечная: без этого композитор
   * не уходит в простой ни на секунду за весь скролл. На бюджетном Android это
   * греет батарею и подтормаживает сам скролл — там, где человек читает
   * аргументы и решает, платить ли за аудит.
   *
   * Пауза ставится инлайном, снятие — очисткой свойства, а не значением
   * 'running': инлайн-'running' перебил бы CSS-правило .marquee:hover,
   * и лента перестала бы останавливаться под курсором для чтения.
   */
  useEffect(() => {
    const root = sectionRef.current;
    if (!root || typeof IntersectionObserver === 'undefined') return;

    const track = root.querySelector('.marquee');
    if (!track) return;

    const io = new IntersectionObserver(
      entries => {
        for (const entry of entries) {
          track.style.animationPlayState = entry.isIntersecting ? '' : 'paused';
        }
      },
      // Запас в пол-экрана: лента набирает ход до того, как попала в кадр,
      // иначе на входе она выглядит замершей.
      { rootMargin: '50% 0px' },
    );

    io.observe(root);

    return () => {
      io.disconnect();
      track.style.animationPlayState = '';
    };
  }, []);

  return (
    <section ref={sectionRef} className="relative w-full px-5 py-section-tight md:px-8 clip-x">
      <div aria-hidden="true" className="rule-dashed absolute inset-x-0 top-0" />

      {/* Заголовок выключен влево по той же оси max-w-6xl, что и все остальные
          секции. Центрированный блок посреди левовыключенной страницы
          заставлял глаз на каждом экране заново искать начало строки. */}
      <Reveal className="mx-auto mb-9 w-full max-w-6xl">
        <h2 className="text-h2 font-medium text-chalk">{platforms.title}</h2>
        <p className="mt-2.5 max-w-[52ch] text-body text-fog">{platforms.note}</p>
      </Reveal>

      {/* Лента шире текстовой колонки, но не во всю ширину окна: 84rem против
          72rem у заголовка. Разница в 12rem даёт ощущение «ряд продолжается
          за краем», ради которого лента и заводится, и при этом сохраняет
          поля страницы — без них блок отклеивается от остального макета. */}
      <div className="mx-auto w-full max-w-[84rem]">
        <Marquee duration={52} ariaLabel="Платформы, к которым подключаются агенты">
          {platforms.items.map(item => (
            <Item key={item.label} label={item.label} icon={item.icon} />
          ))}
        </Marquee>
      </div>
    </section>
  );
}
